const { test, expect } = require('@playwright/test');
test('undo, backdated details, future rejection, purchase edit and wellness backup', async ({page}, testInfo) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.locator('#record-buttons button').first().click();
  await expect(page.locator('#today-total')).toHaveText('1');
  await page.locator('#toast-undo').click();
  await expect(page.locator('#today-total')).toHaveText('0');
  await page.evaluate(() => setupRecordFields('event', {
    type: categories[0].id, timestamp: new Date().toISOString(), details: {}
  }));
  await expect(page.locator('#edit-quantity')).toHaveValue('');
  await expect(page.locator('#edit-unit')).toHaveValue('');
  await page.getByRole('button',{name:'Aggiungi con dettagli o data passata'}).click();
  await page.locator('#edit-quantity').fill('2');
  await page.locator('#edit-unit').selectOption('unità');
  await page.locator('#edit-context').selectOption('Stress');
  await page.locator('#edit-intensity').selectOption('4');
  const yesterday = await page.evaluate(()=>localDateKey(addDays(new Date(),-1)));
  await page.locator('#timestamp-date').fill(yesterday);
  await page.locator('#timestamp-time').fill('14:30');
  await page.locator('#timestamp-save').click();
  await expect(page.locator('#timestamp-dialog')).not.toBeVisible();
  await expect(page.locator('#today-total')).toHaveText('0');
  await page.locator('[data-page-target="history"]').click();
  await expect(page.locator('#history-list')).toContainText('2 unità');
  await expect(page.locator('#history-list')).toContainText('Stress');
  await page.locator('#history-list .edit-timestamp').first().click();
  await page.locator('#timestamp-date').fill('2099-01-01');
  await page.locator('#timestamp-save').click();
  await expect(page.locator('#timestamp-form-error')).toBeVisible();
  await page.locator('#timestamp-cancel').click();
  await page.locator('[data-page-target="today"]').click();
  await page.locator('#record-expense').click();
  await page.locator('#purchase-type').selectOption('cigarette-pack');
  await page.locator('#purchase-amount').fill('5.50');
  await page.locator('#purchase-timestamp').fill(yesterday+'T12:00');
  await page.locator('#purchase-save').click();
  await page.locator('[data-page-target="history"]').click();
  await page.locator('.purchase-history-item .edit-timestamp').click();
  await page.locator('#edit-amount').fill('6.75');
  await page.locator('#timestamp-save').click();
  await expect(page.locator('.purchase-history-amount')).toContainText('6,75');
  await page.locator('[data-page-target="stats"]').click();
  await page.getByRole('button',{name:'Consapevolezza',exact:true}).click();
  await page.locator('#wellness-controls summary').click();
  await page.locator('#monitoring-start').fill(yesterday);
  await page.locator('#weekly-experiment').fill('Osservare le pause dopo pranzo');
  await page.locator('#save-wellness').click();
  await page.locator('#confirm-day').fill(yesterday);
  await page.locator('#confirm-day-button').click();
  await page.locator('#save-craving').click();
  await expect(page.locator('#craving-history')).toContainText('3/5');
  await expect(page.locator('#insight-change')).toHaveText('Dati incompleti');
  const backup = await page.evaluate(() => {
    let output; const original = downloadFile;
    downloadFile = (name, content) => output = JSON.parse(content);
    exportJson(); downloadFile = original;
    return validateBackup(output);
  });
  expect(backup.events[0].details.quantity).toBe(2);
  expect(backup.wellness.cravings).toHaveLength(1);
  expect(backup.wellness.confirmedDays[yesterday]).toBe(true);
  await page.locator('[data-page-target="today"]').click();
  await page.getByRole('button',{name:'Aggiungi con dettagli o data passata'}).click();
  await page.locator('#edit-quantity').fill('1');
  await page.locator('#edit-unit').selectOption('unità');
  await page.locator('#timestamp-date').fill(yesterday);
  await page.locator('#timestamp-time').fill('15:10');
  await page.locator('#timestamp-save').click();
  await expect(page.locator('#toast-message')).toContainText('da rivedere e riconfermare');
  expect(await page.evaluate(date => readWellness().payload.confirmedDays[date], yesterday)).toBeUndefined();
  await page.locator('[data-page-target="stats"]').click();
  await page.locator('#confirm-day-button').click();
  await expect(page.locator('#wellness-status')).toContainText('Giornata confermata');
  await page.locator('[data-page-target="history"]').click();
  await page.locator('.purchase-history-item .edit-timestamp').click();
  await page.locator('#edit-amount').fill('7.25');
  await page.locator('#timestamp-save').click();
  expect(await page.evaluate(date => readWellness().payload.confirmedDays[date], yesterday)).toBeUndefined();
  await page.reload();
  await page.locator('[data-page-target="stats"]').click();
  await expect(page.locator('#weekly-summary')).toContainText('Osservare le pause');
  await page.screenshot({path:testInfo.outputPath('new-features.png'),fullPage:true});
  expect(errors).toEqual([]);
});
