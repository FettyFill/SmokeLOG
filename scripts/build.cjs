// Deterministic, dependency-free bundle. Source files share the legacy lexical
// scope; domain calculations remain standalone and independently testable.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const modules = JSON.parse(fs.readFileSync(path.join(root, 'src/modules.json')));
const bundle = modules.map(name => `// Source: src/${name}\n${fs.readFileSync(path.join(root, 'src', name), 'utf8')}`).join('\n');
const styles = JSON.parse(fs.readFileSync(path.join(root,'src/styles/modules.json'),'utf8'));
fs.writeFileSync(path.join(root,'assets/css/app.css'), styles.map(name => `/* Source: src/styles/${name} */\n${fs.readFileSync(path.join(root,'src/styles',name),'utf8')}`).join('\n'));
fs.writeFileSync(path.join(root, 'app.js'), '// Generated by npm run build. Edit src/, not this file.\n' + bundle);
fs.copyFileSync(path.join(root, 'src/domain/insights.js'), path.join(root, 'insights.js'));
fs.writeFileSync(path.join(root, 'supabase-schema.sql'), ['base.sql','reliability.sql'].map(name => fs.readFileSync(path.join(root,'supabase/schema',name),'utf8')).join('\n'));
const hash = crypto.createHash('sha256');
for (const file of ['index.html','app.js','insights.js','assets/css/app.css','supabase-config.js','privacy.html','terms.html','manifest.webmanifest']) hash.update(fs.readFileSync(path.join(root,file)));
const workerPath = path.join(root,'service-worker.js');
fs.writeFileSync(workerPath, fs.readFileSync(path.join(root,'src/service-worker.js'),'utf8').replace('BUILD_HASH', hash.digest('hex').slice(0,12)));
